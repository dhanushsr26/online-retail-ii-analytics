"""
Step 1b - Profile the RAW data, before any cleaning.

Writes 05_evidence/profile_before.md. Every figure quoted in the report and the
storytelling script must come from this file - nothing is asserted from memory.
"""
import pathlib

import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parent.parent
XLSX = ROOT / "00_source" / "online_retail_II.xlsx"
OUT = ROOT / "05_evidence" / "profile_before.md"
RAW_CACHE = ROOT / "00_source" / "raw_combined.parquet"

CUST = "Customer ID"

# StockCodes that are not products: postage, fees, adjustments, tests, samples.
NON_PRODUCT_CODES = {
    "POST", "D", "M", "C2", "C3", "DOT", "BANK CHARGES", "PADS", "S",
    "TEST001", "TEST002", "AMAZONFEE", "ADJUST", "ADJUST2", "B", "CRUK",
    "GIFT", "SP1002", "DCGSSBOY", "DCGSSGIRL",
}

lines = []


def w(text=""):
    lines.append(text)
    print(text)


def load_raw():
    """Read both sheets, tag each with its source, and cache as parquet."""
    if RAW_CACHE.exists():
        w("_(reading cached `raw_combined.parquet`)_")
        w()
        df = pd.read_parquet(RAW_CACHE)
        for name, grp in df.groupby("SourceSheet"):
            w(f"- Sheet `{name}`: **{len(grp):,}** rows")
        w()
        return df

    sheets = pd.read_excel(XLSX, sheet_name=None,
                           dtype={"Invoice": str, "StockCode": str})
    frames = []
    for name, frame in sheets.items():
        frame = frame.copy()
        frame["SourceSheet"] = name
        frames.append(frame)
        w(f"- Sheet `{name}`: **{len(frame):,}** rows x {frame.shape[1] - 1} columns")
    w()
    combined = pd.concat(frames, ignore_index=True)
    try:
        combined.to_parquet(RAW_CACHE, index=False)
    except Exception as exc:
        w(f"_(parquet cache skipped: {exc})_")
        w()
    return combined


def md(frame, index=False):
    return frame.to_markdown(index=index)


def main():
    w("# Raw Data Profile - Online Retail II")
    w()
    w("Generated by `01_scripts/02_profile_raw.py` **before any cleaning**. "
      "All before/after figures in the report trace back to this file.")
    w()
    w("## 1. Source and shape")
    w()

    df = load_raw()
    value_cols = [c for c in df.columns if c != "SourceSheet"]
    revenue = df["Quantity"] * df["Price"]
    inv = df["Invoice"].astype(str)

    w(f"- **Combined: {len(df):,} rows x {len(value_cols)} columns**")
    w(f"- File: `00_source/{XLSX.name}` ({XLSX.stat().st_size / 1024 / 1024:.1f} MB)")
    w("- SHA256 of source zip: "
      "`572e36277c2390fbfde10664750731e0a86f55e33470d91919085f0408e67bfb`")
    w()

    # ---------------------------------------------------------------- types
    w("## 2. Column data types (as loaded)")
    w()
    types = pd.DataFrame({
        "Column": value_cols,
        "Dtype": [str(df[c].dtype) for c in value_cols],
        "Distinct": [df[c].nunique(dropna=True) for c in value_cols],
        "Example": [repr(df[c].dropna().iloc[0]) if df[c].notna().any() else "-"
                    for c in value_cols],
    })
    w(md(types))
    w()

    # ------------------------------------------------------------- missing
    w("## 3. Missing values")
    w()
    miss = pd.DataFrame({
        "Column": value_cols,
        "Missing": [int(df[c].isna().sum()) for c in value_cols],
    })
    miss["Missing %"] = (miss["Missing"] / len(df) * 100).round(2)
    w(md(miss.sort_values("Missing", ascending=False)))
    w()

    no_cust = df[df[CUST].isna()]
    w(f"### Where is `{CUST}` missing?")
    w()
    w(f"- Rows without a customer: **{len(no_cust):,}** "
      f"({len(no_cust) / len(df) * 100:.2f}% of all rows)")
    rev_nc = (no_cust["Quantity"] * no_cust["Price"]).sum()
    w(f"- Revenue on those rows: **GBP {rev_nc:,.2f}** "
      f"({rev_nc / revenue.sum() * 100:.2f}% of gross revenue) "
      f"- this is why they cannot simply be deleted")
    for sheet, n in no_cust.groupby("SourceSheet").size().items():
        w(f"- `{sheet}`: {n:,} rows")
    w(f"- Of the customer-less rows, "
      f"{no_cust['Invoice'].astype(str).str.startswith('C').mean() * 100:.2f}% "
      f"are cancellations")
    w()

    desc_missing = df[df["Description"].isna()]
    if len(desc_missing):
        w("### Where is `Description` missing?")
        w()
        w(f"- Rows: **{len(desc_missing):,}**")
        top_codes = desc_missing["StockCode"].value_counts().head(10)
        w("- Most common StockCodes on those rows: "
          + ", ".join(f"`{c}` ({n})" for c, n in top_codes.items()))
        w(f"- Share of those rows that also lack a Customer ID: "
          f"{desc_missing[CUST].isna().mean() * 100:.1f}%")
        w(f"- Share with price = 0: {(desc_missing['Price'] == 0).mean() * 100:.1f}%")
        w()

    # ---------------------------------------------------------- duplicates
    w("## 4. Duplicate records")
    w()
    dup_mask = df.duplicated(subset=value_cols, keep="first")
    n_dup = int(dup_mask.sum())
    w(f"- Exact duplicate rows (all {len(value_cols)} columns identical): "
      f"**{n_dup:,}** ({n_dup / len(df) * 100:.2f}%)")
    w(f"- Revenue double-counted by them: **GBP {revenue[dup_mask].sum():,.2f}**")
    w()

    # ------------------------------------------------------------ numerics
    w("## 5. Quantity and Price")
    w()
    stats = df[["Quantity", "Price"]].describe().T
    stats["skew"] = [df["Quantity"].skew(), df["Price"].skew()]
    w(md(stats.round(3).reset_index().rename(columns={"index": "Column"})))
    w()

    checks = [
        ("Quantity < 0 (returns / write-offs)", int((df["Quantity"] < 0).sum())),
        ("Quantity == 0", int((df["Quantity"] == 0).sum())),
        ("Price < 0", int((df["Price"] < 0).sum())),
        ("Price == 0", int((df["Price"] == 0).sum())),
        ("Revenue == 0", int((revenue == 0).sum())),
    ]
    w(md(pd.DataFrame(checks, columns=["Check", "Rows"])))
    w()

    w("### IQR fences and z-score outliers")
    w()
    fence_rows = []
    for col in ("Quantity", "Price"):
        s = df[col].astype(float)
        q1, q3 = s.quantile([0.25, 0.75])
        iqr = q3 - q1
        lo, hi = q1 - 1.5 * iqr, q3 + 1.5 * iqr
        z = (s - s.mean()) / s.std()
        fence_rows.append({
            "Column": col, "Q1": round(q1, 3), "Q3": round(q3, 3),
            "IQR": round(iqr, 3), "Lower fence": round(lo, 3),
            "Upper fence": round(hi, 3),
            "Outside fences": int(((s < lo) | (s > hi)).sum()),
            "abs(z) > 3": int((z.abs() > 3).sum()),
        })
    w(md(pd.DataFrame(fence_rows)))
    w()

    cols = ["Invoice", "StockCode", "Description", "Quantity", "Price", CUST]
    w("### Ten largest absolute quantities")
    w()
    top_q = df.loc[df["Quantity"].abs().sort_values(ascending=False).index[:10], cols]
    w(md(top_q))
    w()

    w("### Ten largest unit prices")
    w()
    w(md(df.nlargest(10, "Price")[cols]))
    w()

    # ------------------------------------------------------- cancellations
    w("## 6. Cancellations and returns")
    w()
    cancel = inv.str.startswith("C")
    w(f"- Invoices beginning `C` (cancellations): **{int(cancel.sum()):,}** rows "
      f"({cancel.mean() * 100:.2f}%)")
    w(f"- Distinct cancellation invoices: **{inv[cancel].nunique():,}**")
    w(f"- Rows with negative quantity: **{int((df['Quantity'] < 0).sum()):,}**")
    w(f"- Negative quantity **without** a `C` invoice: "
      f"**{int(((df['Quantity'] < 0) & ~cancel).sum()):,}** "
      f"- write-offs and stock adjustments rather than customer returns")
    w(f"- Revenue on cancellation rows: **GBP {revenue[cancel].sum():,.2f}**")
    w()

    # --------------------------------------------------------- stock codes
    w("## 7. Non-product StockCodes")
    w()
    codes = df["StockCode"].astype(str)
    is_nonproduct = codes.isin(NON_PRODUCT_CODES) | ~codes.str.match(r"^\d{5}")
    np_rows = df[is_nonproduct]
    w(f"- Rows whose StockCode is not a standard 5-digit product code: "
      f"**{len(np_rows):,}** ({len(np_rows) / len(df) * 100:.2f}%)")
    w(f"- Revenue attached to them: **GBP {revenue[is_nonproduct].sum():,.2f}** "
      f"({revenue[is_nonproduct].sum() / revenue.sum() * 100:.2f}% of gross)")
    w()
    summary = (np_rows.assign(Revenue=np_rows["Quantity"] * np_rows["Price"])
               .groupby("StockCode")
               .agg(Rows=("Invoice", "size"), Revenue=("Revenue", "sum"))
               .sort_values("Rows", ascending=False).head(25).round(2))
    w(md(summary.reset_index()))
    w()

    # ------------------------------------------------------------ country
    w("## 8. Country")
    w()
    ctry = (df.assign(Revenue=revenue)
            .groupby("Country")
            .agg(Rows=("Invoice", "size"), Revenue=("Revenue", "sum"))
            .sort_values("Rows", ascending=False).round(2))
    w(f"- Distinct country labels: **{df['Country'].nunique()}**")
    w()
    w(md(ctry.reset_index()))
    w()

    # --------------------------------------------------------------- dates
    w("## 9. Date coverage")
    w()
    dts = pd.to_datetime(df["InvoiceDate"])
    w(f"- Range: **{dts.min()}** to **{dts.max()}**")
    w(f"- Distinct calendar days: **{dts.dt.date.nunique():,}**")
    w(f"- Hours of day present: {sorted(int(h) for h in dts.dt.hour.unique())}")
    w(f"- Weekdays present: "
      f"{sorted(dts.dt.day_name().unique().tolist())}")
    w()
    per_sheet = df.assign(d=dts).groupby("SourceSheet")["d"].agg(["min", "max", "count"])
    w(md(per_sheet.reset_index()))
    w()
    bounds = {k: (v.min(), v.max()) for k, v in df.assign(d=dts).groupby("SourceSheet")["d"]}
    keys = sorted(bounds)
    if len(keys) == 2:
        a, b = bounds[keys[0]], bounds[keys[1]]
        verdict = "OVERLAP - de-duplication across sheets required" if a[1] >= b[0] \
            else "no overlap - a clean union is safe"
        w(f"- Boundary check between sheets: **{verdict}** "
          f"({keys[0]} ends {a[1]}; {keys[1]} starts {b[0]})")
    w()

    # ------------------------------------------------------------ headline
    w("## 10. Headline figures (raw, uncleaned)")
    w()
    head = [
        ("Rows", f"{len(df):,}"),
        ("Distinct invoices", f"{inv.nunique():,}"),
        ("Distinct StockCodes", f"{df['StockCode'].nunique():,}"),
        ("Distinct customers (non-null)", f"{df[CUST].nunique():,}"),
        ("Distinct countries", f"{df['Country'].nunique():,}"),
        ("Gross revenue (Quantity x Price)", f"GBP {revenue.sum():,.2f}"),
        ("Units (net of returns)", f"{int(df['Quantity'].sum()):,}"),
    ]
    w(md(pd.DataFrame(head, columns=["Metric", "Value"])))
    w()

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWritten: {OUT}")


if __name__ == "__main__":
    main()
